-- [파일 역할]
-- [DB] 사진 업로드 + 앨범 생성 기능에 필요한 테이블/인덱스를 생성하는 Oracle SQL 스크립트
--
-- [관련 기능(화면/요청)]
-- [FRONT] CreatePhotoAlbumPage.jsx
-- [API] POST /api/photos/upload
-- [API] POST /api/albums
--
-- [실행 흐름(순서)]
-- 1) PHOTO 테이블 생성 (업로드된 파일 메타데이터)
-- 2) ALBUM 테이블 생성 (사용자 앨범 본문)
-- 3) ALBUM_PHOTO 연결 테이블 생성 (SLOT_INDEX 포함)
-- 4) ALBUM_TAGS 연결 테이블 생성 (태그 연결)
-- 5) 인덱스 생성

--------------------------------------------------------------------------------
-- 1) PHOTO
--------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE PHOTO (
      PHOTO_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      USER_ID       NUMBER NOT NULL,
      PHOTO_URL     VARCHAR2(500) NOT NULL,
      THUMB_URL     VARCHAR2(500) NOT NULL,
      CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF; -- ORA-00955: 이미 존재
END;
/

BEGIN
  EXECUTE IMMEDIATE '
    ALTER TABLE PHOTO
    ADD CONSTRAINT FK_PHOTO_USER
    FOREIGN KEY (USER_ID)
    REFERENCES USERS(USER_ID)
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-2275, -2261, -2260) THEN RAISE; END IF;
END;
/

--------------------------------------------------------------------------------
-- 2) ALBUM
--------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE ALBUM (
      ALBUM_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      USER_ID       NUMBER NOT NULL,
      TITLE         VARCHAR2(200) NOT NULL,
      BODY_TEXT     CLOB,
      RECORD_DATE   DATE NOT NULL,
      VISIBILITY    VARCHAR2(20) NOT NULL,
      LAYOUT_TYPE   VARCHAR2(50) NOT NULL,
      CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT CHK_ALBUM_VISIBILITY CHECK (VISIBILITY IN (''PUBLIC'', ''FRIENDS'', ''PRIVATE''))
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE '
    ALTER TABLE ALBUM
    ADD CONSTRAINT FK_ALBUM_USER
    FOREIGN KEY (USER_ID)
    REFERENCES USERS(USER_ID)
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-2275, -2261, -2260) THEN RAISE; END IF;
END;
/

--------------------------------------------------------------------------------
-- 3) ALBUM_PHOTO
